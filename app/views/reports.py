import io
import zipfile

import streamlit as st
import ui

from bns.app import evidence
from bns.reporting.report import LIMITATIONS, build_html

ui.page_header("Reports and exports", "Everything a saved run holds, with its label and provenance: configuration, "
               "parameter status, statistics, figures, data files, and a printable report.")
run = ui.pick_run("report-run", kinds=("single_site", "multi_site", "site_plan"))
if run is None:
    st.stop()
ui.development_banner(run.label)
m = run.manifest
if "gba" in str(m["area"].get("variant", "")).lower():
    st.warning("This run uses GlobalBuildingAtlas heights (CC BY-NC 4.0, non-commercial). Do not redistribute its "
               "exports without checking the licence (docs/licensing.md).")

c1, c2 = st.columns(2)
with c1:
    st.subheader("Configuration")
    area = m["area"]
    st.markdown(f"""
| | |
|---|---|
| Run | `{run.run_id}` |
| Kind / mode | {run.kind} / {m.get('mode')} |
| Study area | {area['name']} / {area.get('variant')} — {area.get('role', '')}, approved: {area.get('approved')} |
| Profile | {m['profile']['name']}: {m['profile']['cell_size_m']:g} m cells, {m['profile']['rays_per_site']:.0e} rays |
| Backend | {run.backend} ({(m.get('backend') or {}).get('status', 'production')}) |
| Sites | {len(run.sites)}{' candidates' if run.kind == 'site_plan' else ''} |
| Sensitivity overrides | {m.get('overrides_for_sensitivity') or 'none'} |
""")
with c2:
    st.subheader("Dataset provenance")
    st.markdown(f"""
| | |
|---|---|
| OSM snapshot SHA-256 | `{str(area.get('osm_snapshot_sha256', ''))[:24]}…` |
| Scene fingerprint | `{str(area.get('scene_fingerprint', ''))[:24]}…` |
| Height categories | {', '.join(f"{k} {v:.1f} %" for k, v in (area.get('height_categories_percent') or {}).items())} |
| Fit for research | {area.get('fit_for_research')} |
| Engine | Sionna RT {(m.get('versions') or {}).get('sionna-rt', '?')}, Mitsuba {(m.get('versions') or {}).get('mitsuba', '?')} |
""")

st.subheader("Approval status of the radio parameters")
params = m.get("radio_parameters") or {}
st.dataframe([{"parameter": k, "value": v.get("value") if isinstance(v, dict) else v,
               "status": v.get("status") if isinstance(v, dict) else ""} for k, v in params.items()],
             hide_index=True, use_container_width=True)

st.subheader("Coverage statistics")
st.dataframe([{"scenario": r["scenario"], "GHz": r["frequency_ghz"], "coverage": ui.fmt(r["coverage"], ".1%"),
               "median received power": ui.fmt(r["rx_power_median_dbm"], ".1f", " dBm"),
               "median SINR": ui.fmt(r["sinr_median_db"], ".1f", " dB"), "5th-pct SINR": ui.fmt(r["sinr_p5_db"], ".1f", " dB"),
               "5th-pct Shannon rate": ui.fmt(r["rate_p5_mbps"], ".1f", " Mbit/s"),
               "median Shannon rate": ui.fmt(r["rate_median_mbps"], ".0f", " Mbit/s")} for r in evidence.band_table(run)],
             hide_index=True, use_container_width=True)

if run.kind == "site_plan":
    st.subheader("Site-planning results")
    st.dataframe([{"scenario": next(s["label"] for s in run.scenarios if s["id"] == sid), "selected": ", ".join(r["selected"]),
                   "sites": r["sites"], "coverage": ui.fmt((r["coverage_after"] or [None])[-1], ".1%"),
                   "stop": r["stopped_because"], "uncovered cells": r["uncovered_outdoor_cells"],
                   "sites/km²": round(r["site_density_per_km2"], 1)} for sid, r in run.summary["results"].items()],
                 hide_index=True, use_container_width=True)

validation = evidence.validation_summary(ui.ROOT)
with st.expander("Validation results (latest TR 38.901 comparison)"):
    if validation is None:
        st.caption("None saved.")
    else:
        ui.markdown_file(validation["folder"] / "summary.md")

notes = {name: run.path / name for name in ("summary.md", "sensitivity.md", "backend_agreement.md",
                                            "near_site_nr_28000.md") if (run.path / name).exists()}
for name, path in notes.items():
    with st.expander(name):
        ui.markdown_file(path)

pngs = sorted(run.path.glob("*.png"))
if pngs:
    st.subheader("Figures")
    pick = st.selectbox("Figure", pngs, format_func=lambda p: p.name)
    st.image(str(pick))
    st.download_button("Download this figure (PNG)", pick.read_bytes(), file_name=pick.name, mime="image/png")
else:
    st.caption("No figures in this run folder (PNG files are regenerated by the scripts and are not in git).")

st.subheader("Exports")
csvs = sorted(run.path.glob("*.csv"))
e1, e2, e3 = st.columns(3)
with e1:
    st.markdown("**Data (CSV)**")
    if not csvs:
        st.caption("No CSV in this run.")
    for p in csvs:
        st.download_button(p.name, p.read_bytes(), file_name=p.name, mime="text/csv", key=f"csv-{p.name}")
with e2:
    st.markdown("**Reproducibility**")
    st.download_button("manifest.json", (run.path / "manifest.json").read_bytes(), file_name="manifest.json",
                       mime="application/json")
    st.download_button("summary.json", (run.path / "summary.json").read_bytes(), file_name="summary.json",
                       mime="application/json")
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for p in run.path.iterdir():
            if p.is_file() and p.suffix != ".npz":
                z.write(p, p.name)
    st.download_button("Whole run folder (ZIP, without arrays)", buf.getvalue(), file_name=f"{run.run_id}.zip",
                       mime="application/zip")
with e3:
    st.markdown("**Printable report**")
    extra = {"Latest TR 38.901 comparison": (validation["folder"] / "summary.md").read_text(encoding="utf-8")} \
        if validation else {}
    html = build_html(run.path, extra_markdown=extra, invalid_reason=run.invalid)
    st.download_button("Report (HTML, print to PDF)", html.encode("utf-8"), file_name=f"report-{run.run_id}.html",
                       mime="text/html")
    st.caption("Self-contained; keeps the label, provenance and the limitations below.")

st.subheader("Scientific limitations (included in every report)")
for line in LIMITATIONS:
    st.markdown(f"- {line}")
