"""Prepare the MATLAB cross-check package from a saved TR 38.901 validation run (no MATLAB here).

    uv run python scripts/export_matlab_case.py VALIDATION_RUN_DIR [--scenario UMa] [--per-class 100]

Writes validation/matlab/<case>/ with:
  scene.stl            buildings + ground, scene coordinates in metres (x east, y north, z up)
  case.json            transmitter, frequencies, materials, mechanisms, engine settings
  receivers.csv        receiver points (cell centres) with the Sionna path gain per band and LOS class
  run_case.m           MATLAB script: SBR ray tracing at the same points, writes matlab_results.csv
  README.md            how to run it and what differs between the two engines
Compare afterwards with scripts/compare_matlab.py. Nothing is claimed verified until that has run.
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
from pathlib import Path

import numpy as np

from bns.core.units import linear_to_db
from bns.simulation.cache import PathGainCache
from bns.simulation.experiment import load_scenarios
from bns.validation.matlab_case import merge, read_ply, sample_cells, write_stl

ROOT = Path(__file__).resolve().parents[1]
BANDS = ("nr_3500", "nr_28000")         # one mid band, one mmWave band

MATLAB = r"""%% Baghdad Network Simulator - MATLAB cross-check, case {case}
% Generated by scripts/export_matlab_case.py. Requires Antenna Toolbox / Communications Toolbox
% ray tracing (propagationModel "raytracing", Method "sbr"). Check the name-value arguments
% against your MATLAB release; the settings below mirror case.json.
here = fileparts(mfilename("fullpath"));
tri = stlread(fullfile(here, "scene.stl"));
rx = readtable(fullfile(here, "receivers.csv"), "CommentStyle", "#");
txPos = [{tx_x}; {tx_y}; {tx_z}];
freqs = [{freqs}];
pm = propagationModel("raytracing", "CoordinateSystem", "cartesian", "Method", "sbr", ...
    "MaxNumReflections", {reflections}, "MaxNumDiffractions", {diffractions}, ...
    "SurfaceMaterial", "concrete", "AngularSeparation", "low");
results = table();
for k = 1:numel(freqs)
    tx = txsite("cartesian", "AntennaPosition", txPos, "TransmitterFrequency", freqs(k), ...
        "Antenna", "isotropic", "TransmitterPower", 1);
    sites = rxsite("cartesian", "AntennaPosition", [rx.x_m.'; rx.y_m.'; rx.z_m.'], "Antenna", "isotropic");
    rays = raytrace(tx, sites, pm, "Map", tri);
    pl_incoherent = nan(height(rx), 1);   % sum of ray powers, as Sionna's radio map (non-coherent)
    nrays = zeros(height(rx), 1);
    for i = 1:height(rx)
        r = rays{{i}};
        nrays(i) = numel(r);
        if ~isempty(r)
            pl_incoherent(i) = -10 * log10(sum(10 .^ (-[r.PathLoss] / 10)));
        end
    end
    results = [results; table(rx.id, repmat(freqs(k), height(rx), 1), pl_incoherent, nrays, ...
        'VariableNames', {{'id', 'frequency_hz', 'matlab_pathloss_db', 'matlab_rays'}})]; %#ok<AGROW>
end
writetable(results, fullfile(here, "matlab_results.csv"));
fprintf("Wrote %d rows to matlab_results.csv\n", height(results));
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("run", type=Path)
    parser.add_argument("--scenario", default="UMa")
    parser.add_argument("--per-class", type=int, default=100)
    args = parser.parse_args()
    args.run = args.run.resolve()
    manifest = json.loads((args.run / "manifest.json").read_text(encoding="utf-8"))
    summary = json.loads((args.run / "summary.json").read_text(encoding="utf-8"))
    from bns.geospatial.grid import Grid
    from bns.geospatial.grid import outdoor_mask
    from bns.geospatial import pipeline
    from bns.geospatial.study_area import load_study_areas

    g = manifest["grid"]
    grid = Grid(tuple(g["center_xy"]), tuple(g["size_xy"]), g["cell_size_m"], g["height_m"])
    area = load_study_areas(ROOT / "configs" / "study_area.yaml")[manifest["area"]["name"]]
    scene_dir = ROOT / "data" / "scenes" / area.name / manifest["area"]["variant"]
    outdoor = outdoor_mask(grid, [b.polygon for b in pipeline.load_buildings(scene_dir, area)])
    tx = summary[args.scenario]["bs_position_m"]
    cache = PathGainCache(ROOT / "data" / "cache" / "pathgain")
    keys = manifest["jobs"][args.scenario]
    los = cache.get(keys["los_only"])[0] > 0
    gains = {b: cache.get(keys["bands"][b])[0] for b in BANDS}
    xs, ys = np.meshgrid(grid.x_centers, grid.y_centers)
    d2d = np.hypot(xs - tx[0], ys - tx[1])
    usable = outdoor & (d2d >= 10.0) & np.all([gains[b] > 0 for b in BANDS], axis=0)
    cells = sample_cells(usable, los.astype(int), args.per_class, seed=0)

    case = f"{args.scenario.lower()}-{area.name}-{manifest['area']['variant']}"
    out = ROOT / "validation" / "matlab" / case
    out.mkdir(parents=True, exist_ok=True)
    write_stl(out / "scene.stl", *merge([read_ply(p) for p in sorted((scene_dir / "meshes").glob("*.ply"))]), name=case)
    scenarios = {s["id"]: s for s in load_scenarios(ROOT)}
    with open(out / "receivers.csv", "w", newline="", encoding="utf-8") as f:
        f.write(f"# {manifest['label']}; Sionna values are cell averages over {grid.cell_size_m:g} m cells\n")
        w = csv.writer(f)
        w.writerow(["id", "x_m", "y_m", "z_m", "d2d_m", "los", *[f"sionna_pathloss_db_{b}" for b in BANDS]])
        for n, (iy, ix) in enumerate(cells, start=1):
            w.writerow([n, f"{xs[iy, ix]:.2f}", f"{ys[iy, ix]:.2f}", f"{grid.height_m:.2f}", f"{d2d[iy, ix]:.1f}",
                        int(los[iy, ix]), *[f"{-linear_to_db(gains[b][iy, ix]):.2f}" for b in BANDS]])
    mech = manifest["mechanisms"]
    spec = {"label": manifest["label"], "case": case, "source_run": str(args.run.relative_to(ROOT)),
            "coordinates": "scene metres: x east, y north, z up; origin at the study-area centre "
                           f"({area.center_lat}, {area.center_lon}), local transverse Mercator",
            "transmitter": {"position_m": tx, "antenna": "isotropic", "polarization": "V", "power_w": 1},
            "frequencies_hz": [scenarios[b]["frequency_hz"] for b in BANDS], "bands": list(BANDS),
            "receivers": {"count": len(cells), "height_m": grid.height_m, "antenna": "isotropic",
                          "selection": f"up to {args.per_class} LOS and {args.per_class} NLOS outdoor cell centres, seed 0"},
            "materials": {"buildings": "ITU-R P.2040 concrete, 0.2 m slab in Sionna",
                          "ground": "ITU-R P.2040 concrete, 1.0 m slab in Sionna"},
            "mechanisms": mech, "sionna": {"profile": manifest["profile"], "engine": "Sionna RT 2.2.0, RadioMapSolver"},
            "expected_metrics": ["mean, median and RMSE of MATLAB minus Sionna path loss, per band and LOS class",
                                 "share of receivers reached by one engine only"]}
    (out / "case.json").write_text(json.dumps(spec, indent=2), encoding="utf-8")
    (out / "run_case.m").write_text(MATLAB.format(case=case, tx_x=tx[0], tx_y=tx[1], tx_z=tx[2],
                                                  freqs=", ".join(f"{scenarios[b]['frequency_hz']:.6g}" for b in BANDS),
                                                  reflections=mech["max_depth"], diffractions=1), encoding="utf-8")
    (out / "README.md").write_text(f"""# MATLAB cross-check, case `{case}`

**Status: prepared, not executed.** MATLAB is not installed on the development PC; run this on
the laptop that has MATLAB. Nothing is verified until `scripts/compare_matlab.py` has run on the
results. {manifest['label']}.

## What is compared

Path loss between isotropic antennas from one transmitter at {tx[2]:g} m ({args.scenario}
configuration of `{spec['source_run']}`) to {len(cells)} receivers at {grid.height_m:g} m, at
{', '.join(f"{scenarios[b]['frequency_hz'] / 1e9:g} GHz" for b in BANDS)}. Identical geometry (`scene.stl`,
exported from the same meshes Sionna traced), materials (concrete), transmitter and receiver
coordinates (`case.json`, `receivers.csv`).

## Run

1. Copy this folder to the laptop. Open MATLAB in it.
2. `run_case` — writes `matlab_results.csv` (one row per receiver and frequency).
3. Copy `matlab_results.csv` back into this folder and run
   `uv run python scripts/compare_matlab.py validation/matlab/{case}`.

## Known differences between the engines (expect disagreement from these, not only from errors)

| Aspect | Sionna RT (project) | MATLAB SBR |
|---|---|---|
| Quantity | cell average over {grid.cell_size_m:g} m cells, non-coherent | point receiver; `run_case.m` sums ray powers non-coherently to match |
| Reflections | up to {mech['max_depth']} | `MaxNumReflections` {mech['max_depth']} |
| Diffraction | first-order, never combined with a reflection, randomly sampled wedges | `MaxNumDiffractions` 1 (UTD); may combine with reflections depending on release |
| Materials | ITU-R P.2040 concrete as a slab (buildings 0.2 m, ground 1.0 m) | ITU-R P.2040 concrete, half-space |
| Transmission through walls | off | not modelled |
| Ray launching | Fibonacci lattice, {manifest['profile']['rays_per_site']:.0e} rays | SBR angular separation "low" (about 0.2°) |

Agreement criterion (to be agreed with the supervisor, decision B1): for example median
|difference| within the convergence floor of the profile (about 2 dB) in LOS cells.
""", encoding="utf-8")
    print(f"OUTPUT {out} ({len(cells)} receivers)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
